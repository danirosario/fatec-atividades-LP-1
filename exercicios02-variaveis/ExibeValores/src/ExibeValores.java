public class ExibeValores 
{
	public static void main (String[] args) 
	{
		byte  a = 19;
		short b = 1_571;
		int   c = 100_000;
		long  d = 2_147_483_648L;
		float e = 4.14F;
		float f = 3.14_159_265_358_979F;
		boolean bool = true;
		char letra = 'K';  
		
		System.out.println("Valor 01: byte    -> " + a);
		System.out.println("Valor 02: short   -> " + b);
		System.out.println("Valor 03: int     -> " + c);
		System.out.println("Valor 04: long    -> " + d);
		System.out.println("Valor 05: float   -> " + e);
		System.out.println("Valor 06: float   -> " + f);
		System.out.println("Valor 07: boolean -> " + bool);
		System.out.println("Valor 08: char    -> " + letra);
		
	}
}
