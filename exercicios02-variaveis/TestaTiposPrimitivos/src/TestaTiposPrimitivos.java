public class TestaTiposPrimitivos 
{	
	public static void main (String[] args) 
	{
		byte    tipoPrimitivoByte    = 120;
		short   tipoPrimitivoShort   = 32000;
		int     tipoPrimitivoInt     = 2_000_000_000;
		long    tipoPrimitivoLong    = 123_456_789_000_000L;
		float   tipoPrimitivoFloat   = 150.50F;
		double  tipoPrimitivoDouble  = 123_000.90;
		char    tipoPrimitivoChar    = 'A';
		boolean tipoPrimitivoBoolean = true;
		
		System.out.println("Tipos Primitivos JAVA:\n");
		
		System.out.println("byte:    " + tipoPrimitivoByte);
		System.out.println("short:   " + tipoPrimitivoShort);
		System.out.println("int:     " + tipoPrimitivoInt);
		System.out.println("long:    " + tipoPrimitivoLong);
		System.out.println("float:   " + tipoPrimitivoFloat);
		System.out.println("double:  " + tipoPrimitivoDouble);
		System.out.println("char:    " + tipoPrimitivoChar);
		System.out.println("boolean: " + tipoPrimitivoBoolean);	
	}
}
