public class lista06_exercicio28 
{	
	public static void main (String[] args) 
	{
		for (int i = 1; i <= 10; i++) 
        {
            System.out.print(i + ", ");
            for (int j = 1 + i; j <= 10; j++) 
            {
                System.out.print(j + " ");
            }
            System.out.println();
        }
	}
}

