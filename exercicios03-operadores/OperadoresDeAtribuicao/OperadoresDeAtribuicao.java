public class OperadoresDeAtribuicao 
{
	public static void main (String[] args) 
	{
		int a = 1; // a = 1
		System.out.println(a);
		
		a += 2; // a = 3
		System.out.println(a);
		
		a -= 1; // a = 2
		System.out.println(a);
		
		a *= 3; // a = 6
		System.out.println(a);
		
		a /= 2; // a = 3
		System.out.println(a);
		
		a %= 2; // a = 1
		System.out.println(a);
		
		a ++; // a = 2
		System.out.println(a);
		
		a --; // a = 1
		System.out.println(a);
	}
}

